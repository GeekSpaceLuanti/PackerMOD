local source = assert(core.settings:get("packermod_source_path"))
local config = assert(core.settings:get("packermod_smoke_config"))
core.settings:set("keymap_backward", "SYSTEM_SCANCODE_82")
dofile(source .. "/mainmenu/init.lua")
local bindings = Settings(config)
assert(bindings:get("keymap_backward") == "SYSTEM_SCANCODE_82", "Custom binding was overwritten")
assert(bindings:get("keymap_inventory") == "SYSTEM_SCANCODE_8", "Java inventory key was not set")
assert(bindings:get("keymap_aux1") == "SYSTEM_SCANCODE_224", "Java auxiliary key was not set")
assert(bindings:get("keymap_screenshot") == "SYSTEM_SCANCODE_59" and bindings:get("keymap_toggle_chat") == "")
assert(bindings:get("keymap_toggle_debug") == "SYSTEM_SCANCODE_60" and bindings:get("keymap_toggle_fog") == "")
assert(bindings:get("keymap_camera_mode") == "SYSTEM_SCANCODE_62")
local controller = packermod.dialogs.dlg_settings
local dlg = controller.show(packermod.library.dlg())
local data, handle = dlg.data, controller._internal.handler
local function render() return controller._internal.get_formspec(data) end
local function search(query)
    handle(dlg, { settings_search = "true", settings_query = query }); render()
end
search("video_driver"); assert(#data.row_entries == 0, "Expert setting exposed by search")
handle(dlg, { settings_show_advanced = "true" }); search("video_driver")
assert(#data.row_entries == 1)
search("keymap_quicktune_prev"); assert(#data.row_entries == 0, "Developer key exposed by expert switch")
handle(dlg, { settings_show_developer = "true" }); search("keymap_quicktune_prev")
assert(#data.row_entries == 1)
assert(Settings(config):get("packermod_show_advanced") == "true")
assert(Settings(config):get("packermod_show_developer") == "true")
local reopened = controller.show(dlg)
assert(reopened.data.show_advanced and reopened.data.show_developer, "Visibility switches forgotten on reopening")
reopened:delete(); dlg:show()
handle(dlg, { settings_show_advanced = "true" })
handle(dlg, { settings_show_developer = "true" })
handle(dlg, { settings_tab_keymap = "true" }); render()
assert(#data.row_entries > 8 and not render():find("settings_next", 1, true), "Keys were paginated")
handle(dlg, { settings_row_1 = "KEY_UP" })
assert(Settings(config):has("keymap_forward"))
handle(dlg, { settings_reset_1 = "true" })
assert(not Settings(config):has("keymap_forward"))
handle(dlg, { settings_tab_controls = "true" }); render()
for _,e in ipairs(data.home_entries) do assert(e.type ~= "key", "Key binding outside Keymap") end
handle(dlg, { settings_tab_general = "true" }); render()
assert(data.row_entries[2].name == "pm_gui_scale")
for _, entry in ipairs(data.row_entries) do assert(entry.name ~= "pm_button_scale" and entry.name ~= "pm_font_scale") end
handle(dlg, { settings_row_2 = "4" }); render()
assert(core.settings:get("packermod_gui_size") == "large")
assert(tonumber(core.settings:get("gui_scaling")) == 1.25)
assert(tonumber(core.settings:get("font_size")) == 16)
assert(not Settings(config):has("packermod_button_scale"))
local reopened_size = controller.show(dlg)
assert(core.settings:get("packermod_gui_size") == "large")
reopened_size:delete(); dlg:show()
handle(dlg, { settings_reset_2 = "true" }); render()
assert(Settings(config):get("packermod_gui_size") == "auto")
assert(tonumber(core.settings:get("font_size")) == 16)
handle(dlg, { settings_tab_audio = "true" }); render()
handle(dlg, { settings_row_1 = "CHG:420" })
handle(dlg, { settings_row_3 = "true", settings_row_1 = "VAL:420" })
handle(dlg, { settings_reset_1 = "true", settings_list_scroll = "VAL:0" })
assert(not Settings(config):has("sound_volume") and Settings(config):get("mute_sound") == "true")
handle(dlg, { settings_reset_3 = "true" })
handle(dlg, { settings_tab_general = "true" })
ui.update()
core.log("action", "PackerMOD: settings UI verified")
