function M.language()
    local settings = core and core.settings
    return settings and settings:get("packermod_language") == "en" and "en" or "ja"
end
function M.t(text, ...)
    local value = M.language() == "ja" and (ja[text] or text) or text
    if select("#", ...) > 0 then return string.format(value, ...) end
    return value
end
function M.set(language)
    if language ~= "ja" and language ~= "en" then return false end
    core.settings:set("packermod_language", language)
    core.settings:set("language", language)
    core.settings:write()
    return true
end
function M.message(text)
    if M.language() == "en" or not text then return text end
    if ja[text] then return ja[text] end
    local prefixes = {
        ["Minimum: "] = "最小値: ",
        ["Maximum: "] = "最大値: ",
        ["Unknown flag: "] = "使用できないフラグ: ",
        ["Search failed: "] = "検索に失敗しました: ",
        ["Save failed: "] = "保存に失敗しました: ",
        ["Add failed: "] = "追加に失敗しました: ",
        ["Remove failed: "] = "削除に失敗しました: ",
        ["Create failed: "] = "作成に失敗しました: ",
        ["Delete failed: "] = "削除に失敗しました: ",
        ["Import failed: "] = "取り込みに失敗しました: ",
        ["Saved pack: "] = "パックを作成しました: ",
        ["Imported pack: "] = "パックを取り込みました: ",
        ["Added "] = "追加しました: ",
    }
    for prefix, translated in pairs(prefixes) do
        if text:sub(1, #prefix) == prefix then return translated .. M.message(text:sub(#prefix + 1)) end
    end
    local count = text:match("^Found (%d+) results%.$")
    if count then return count .. "件見つかりました。" end
    return text
end
return M
